// Offline generator. Inputs: categories.json and this Node's ICU Unicode data.
// Run at repository root: node tools/unicode/gen-tables.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
const names = JSON.parse(readFileSync(new URL('categories.json', import.meta.url)));
// D243: ECMAScript/Node ICU exposes General_Category but no Block property.
// Never infer block ranges from scripts/categories. An authoritative pinned
// block-name/range input is needed before the compiler can accept IsBlock.
for (const flag of ['u', 'v']) {
  let supported = false;
  try { new RegExp('\\p{Block=Basic_Latin}', flag); supported = true; } catch (e) {
    if (!(e instanceof SyntaxError)) throw e;
  }
  if (supported) throw new Error('Block properties are now exposed; review D243 and pin block data before regenerating');
}
const id = s => s.charCodeAt(0) * 256 + (s.charCodeAt(1) || 0);
const ranges = [], packed = [];
function vint(n) { do { const b = n & 127; n >>>= 7; packed.push(b | (n ? 128 : 0)); } while (n); }
for (const name of [...names].sort((a, b) => id(a) - id(b))) {
  const re = new RegExp(`^\\p{gc=${name}}$`, 'u');
  const pairs = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    // RFC 9485 text is Unicode scalar values: Cs is empty, even in C.
    const yes = cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (yes && start < 0) start = cp;
    if (!yes && start >= 0) { pairs.push([start, cp - 1]); start = -1; }
  }
  vint(id(name)); vint(pairs.length);
  let next = 0;
  for (const [lo, hi] of pairs) {
    vint(lo - next); vint(hi - lo); next = hi + 1;
    ranges.push(id(name), lo, hi);
  }
}
const header = `Generated by tools/unicode/gen-tables.mjs; Node ${process.version}; Unicode ${process.versions.unicode}. DO NOT EDIT.`;
const js = `// ${header}
// Unsigned varints: category id, range count, then (lo - previous hi - 1, hi - lo).
export const nodeVersion = ${JSON.stringify(process.version)};
export const unicodeVersion = ${JSON.stringify(process.versions.unicode)};
export const categories = Object.freeze(${JSON.stringify(names)});
const packed = ${JSON.stringify(Buffer.from(packed).toString('base64'))};
const bytes = Uint8Array.from(atob(packed), c => c.charCodeAt(0));
let at = 0;
function vint() {
  let n = 0, shift = 0, b;
  do { b = bytes[at++]; n |= (b & 127) << shift; shift += 7; } while (b & 128);
  return n;
}
const out = [];
while (at < bytes.length) {
  const id = vint(), count = vint();
  let next = 0;
  for (let i = 0; i < count; i++) {
    const lo = next + vint(), hi = lo + vint();
    out.push(id, lo, hi); next = hi + 1;
  }
}
/** Compile-time-only, sorted [category id, lo, hi] triples. Treat as immutable. */
export const tables = Int32Array.from(out);
`;
const rows = [];
for (let i = 0; i < packed.length; i += 32) rows.push('    ' + packed.slice(i, i + 32).join(',') + ',');
const rs = `// ${header}
pub const NODE_VERSION: &str = ${JSON.stringify(process.version)};
pub const UNICODE_VERSION: &str = ${JSON.stringify(process.versions.unicode)};
static PACKED: &[u8] = &[\n${rows.join('\n')}\n];
fn vint(at: &mut usize) -> i32 {
    let mut n = 0; let mut shift = 0;
    loop {
        let b = PACKED[*at]; *at += 1;
        n |= ((b & 127) as i32) << shift;
        if b & 128 == 0 { return n; }
        shift += 7;
    }
}
/// Compile-time-only sorted [category id, lo, hi] triples, identical to snug/unicode.
pub fn tables() -> Vec<i32> {
    let mut out = Vec::with_capacity(${ranges.length});
    let mut at = 0;
    while at < PACKED.len() {
        let id = vint(&mut at); let count = vint(&mut at);
        let mut next = 0;
        for _ in 0..count {
            let lo = next + vint(&mut at); let hi = lo + vint(&mut at);
            out.extend_from_slice(&[id, lo, hi]); next = hi + 1;
        }
    }
    out
}
`;
for (const [path, data] of [['host/js/src/unicode-tables.mjs', js], ['host/rust/src/unicode_tables.rs', rs]]) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8') !== data) throw new Error(`stale ${path} (generator runtime must match pinned Node/Unicode)`);
  } else writeFileSync(url, data);
}
console.log(`${names.length} categories, ${ranges.length / 3} ranges, ${packed.length} packed bytes; Node ${process.version}, Unicode ${process.versions.unicode}`);
console.log('Block tables unavailable from this pinned Node API; XSD IsBlock escapes are explicitly refused (D243).');
